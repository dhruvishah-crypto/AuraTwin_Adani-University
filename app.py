    tab_overview, tab_signals, tab_forecast, tab_timeline, tab_whatif, tab_early_warning = st.tabs(
        [
            "1️⃣ Patient Overview",
            "2️⃣ Multimodal Signals",
            "3️⃣ Risk Forecast & Explanation",
            "4️⃣ Twin History Timeline",
            "5️⃣ What-If Laboratory",
            "🚨 Early-Warning Evaluation",
        ]
    )

    # -------------------------------------------------------------------------
    # PANEL 1: Patient Overview
    # -------------------------------------------------------------------------
    with tab_overview:
        # Visible Synthetic Patient Banner
        st.markdown(
            """
            <div class="banner-synthetic">
                <div>
                    <span style="font-size: 16px; font-weight: 700; color: #fbbf24;">⚠️ SYNTHETIC PATIENT RECORD</span><br/>
                    <span style="font-size: 13px; color: #cbd5e1;">
                        Profile generated via synthetic EHR & epidemiological simulator. No real-world Protected Health Information (PHI) is present.
                    </span>
                </div>
                <div>
                    <span class="badge-provenance badge-synthetic">Synthetic Demo</span>
                    <span class="badge-provenance badge-ehr">EHR Baseline</span>
                </div>
            </div>
            """,
            unsafe_allow_html=True,
        )

        pat_row = patients_df[patients_df["patient_id"] == patient_id]
        if not pat_row.empty:
            p_data = pat_row.iloc[0].to_dict()
        else:
            p_data = {
                "patient_id": patient_id,
                "age": 42,
                "sex": "F",
                "asthma_severity": "Moderate Persistent",
                "baseline_resp_rate": 16.0,
                "baseline_spo2": 96.0,
                "comorbidities": "Allergic Rhinitis",
                "controller_prescribed": "Fluticasone/Salmeterol 250/50",
                "prior_exacerbations_12m": 2,
                "pollution_sensitivity": "High",
            }

        c1, c2, c3, c4 = st.columns(4)
        c1.metric("Patient ID", p_data.get("patient_id", patient_id))
        c1.write(f"**Age / Sex:** {p_data.get('age', 42)} y / {p_data.get('sex', 'F')}")
        c2.metric("Clinical Severity", str(p_data.get("asthma_severity", "Moderate")))
