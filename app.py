def main() -> None:
    metrics = load_metrics()
    whatif_effects = load_whatif_effects()
    replay_catalog = load_replay_data()
    patients_df = load_cohort_patients()
    twin = get_digital_twin_predictor()

    # -------------------------------------------------------------------------
    # Sidebar: Patient Selection & Replay Controls
    # -------------------------------------------------------------------------
    st.sidebar.image("https://img.icons8.com/fluency/96/lungs.png", width=64)
    st.sidebar.title("Twin Controls")

    # Replay Patient Control
    st.sidebar.markdown("### ⏱️ Replay Patient Control")
    st.sidebar.caption("Stream recorded test-set observations hour by hour through the digital twin.")

    replay_options = {
        "non_silent_pt0001": "Episode A: Non-Silent (PT0001 - Aug 4)",
        "silent_pt0001": "Episode B: Silent Anticipated (PT0001 - Aug 14)",
        "silent_missed_pt0008": "Episode C: Silent Missed (PT0008 - Sep 20)",
    }
    selected_replay_key = st.sidebar.selectbox(
        "Select Test-Set Replay Scenario",
        options=list(replay_options.keys()),
        format_func=lambda k: replay_options[k],
        help="Preloaded real episodes from the holdout TEST split, replayed 48h before onset to 12h after.",
    )

    replay_obj = replay_catalog.get(selected_replay_key, {})
    records = replay_obj.get("records", [])
    total_steps = len(records)
    metadata = replay_obj.get("metadata", {})
    patient_id = metadata.get("patient_id", "PT0001")

    # Evaluation view toggle (off by default per Requirement 3)
    eval_view = st.sidebar.toggle(
        "Show Evaluation Ground Truth",
        value=False,
        help="Reveals simulator ground truth onset marker (off by default to simulate real clinical deployment).",
    )

    # Step slider / replay stream
    if "step_idx" not in st.session_state:
        st.session_state.step_idx = 48  # Default at onset or near onset for immediate visibility

    col_btn1, col_btn2, col_btn3 = st.sidebar.columns([1, 1, 1])
    with col_btn1:
        if st.button("⏮️ Start"):
            st.session_state.step_idx = 0
    with col_btn2:
        if st.button("◀️ -1h"):
            st.session_state.step_idx = max(0, st.session_state.step_idx - 1)
    with col_btn3:
        if st.button("▶️ +1h"):
            st.session_state.step_idx = min(total_steps - 1, st.session_state.step_idx + 1)

    step_idx = st.sidebar.slider(
        "Replay Observation Hour",
        min_value=0,
        max_value=max(0, total_steps - 1),
        value=min(st.session_state.step_idx, max(0, total_steps - 1)),
        format="Hour %d",
        help="Step index along the 61-hour timeline (48 hours pre-onset, 12 hours post-onset).",
    )
    st.session_state.step_idx = step_idx

    current_record = records[step_idx] if records else {}
    current_time_str = current_record.get("timestamp", "2026-08-04 10:00:00")
    rel_hour = current_record.get("relative_hour", 0)

    st.sidebar.markdown(
        f"""
        <div style="background: #1e293b; padding: 10px; border-radius: 6px; font-size: 13px; margin-top: 10px;">
            <b>Active Time:</b> {current_time_str}<br/>
            <b>Relative Hour:</b> <span style="color: {'#ef4444' if rel_hour >= 0 else '#38bdf8'}"><b>{rel_hour:+d}h</b></span> relative to onset<br/>
            <b>Silent Episode:</b> {'Yes (No Prodrome)' if metadata.get('is_silent') else 'No (Classic)'}
        </div>
        """,
        unsafe_allow_html=True,
    )

    # Render Header
    render_header(current_time_str)

