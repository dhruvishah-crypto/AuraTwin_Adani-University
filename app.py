@st.cache_data
def load_metrics() -> Dict[str, Any]:
    metrics_path = WORKSPACE_ROOT / "models" / "metrics.json"
    if not metrics_path.is_file():
        return {}
    with open(metrics_path, "r", encoding="utf-8") as f:
        return json.load(f)


@st.cache_data
def load_whatif_effects() -> Dict[str, Any]:
    effects_path = WORKSPACE_ROOT / "models" / "whatif_effects.json"
    if not effects_path.is_file():
        return {}
    with open(effects_path, "r", encoding="utf-8") as f:
        return json.load(f)


@st.cache_data
def load_replay_data() -> Dict[str, Any]:
    replay_path = WORKSPACE_ROOT / "data" / "replay_episodes.json"
    if not replay_path.is_file():
        return {}
    with open(replay_path, "r", encoding="utf-8") as f:
        return json.load(f)


@st.cache_data
def load_cohort_patients() -> pd.DataFrame:
    for candidate in [
        WORKSPACE_ROOT / "data" / "patients.csv",
        WORKSPACE_ROOT / "data" / "sample_patients.csv",
    ]:
        if candidate.is_file():
            return pd.read_csv(candidate)
    return pd.DataFrame()


@st.cache_resource
def get_digital_twin_predictor():
    from src.digital_twin import DigitalTwin
    return DigitalTwin(data_dir=WORKSPACE_ROOT / "data")


