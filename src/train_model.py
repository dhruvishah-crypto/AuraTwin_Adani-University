class CalibratedModel:
    """Wrapper encapsulating a base Pipeline and a post-hoc calibrator.

    The base model is fit on train; the calibrator is fit strictly on validation.
    """

    def __init__(self, base_pipeline: Pipeline, calibrator: Any, method: str = "isotonic") -> None:
        self.base_pipeline = base_pipeline
        self.calibrator = calibrator
        self.method = method

    def predict_proba(self, X: Union[np.ndarray, pd.DataFrame]) -> np.ndarray:
        """Predict calibrated probabilities."""
        raw_prob = self.base_pipeline.predict_proba(X)[:, 1]
        if hasattr(self.calibrator, "predict_proba"):
            cal_prob = self.calibrator.predict_proba(raw_prob.reshape(-1, 1))[:, 1]
        elif hasattr(self.calibrator, "predict"):
            cal_prob = self.calibrator.predict(raw_prob)
        else:
            cal_prob = raw_prob
        cal_prob = np.clip(np.nan_to_num(cal_prob, nan=0.0), 0.0, 1.0)
        return np.column_stack([1.0 - cal_prob, cal_prob])

    def predict(self, X: Union[np.ndarray, pd.DataFrame], threshold: float = 0.5) -> np.ndarray:
        """Predict binary labels at a specified decision threshold."""
        prob = self.predict_proba(X)[:, 1]
        return (prob >= threshold).astype(int)


def stratified_patient_split(
    df: pd.DataFrame,
    train_frac: float = 0.70,
    val_frac: float = 0.15,
    test_frac: float = 0.15,
    seed: int = 42,
) -> Tuple[pd.DataFrame, pd.DataFrame, pd.DataFrame, Dict[str, Any]]:
    """Perform a patient-level split stratified by patient-specific event rates.

    Guarantees zero data leakage: each patient's data resides entirely in one split.
    """
    patient_stats = (
        df.groupby("patient_id")
        .agg(
            event_rate=("event_next_24h", "mean"),
            total_hours=("event_next_24h", "count"),
        )
        .reset_index()
    )

    try:
        patient_stats["stratum"] = pd.qcut(patient_stats["event_rate"], q=4, labels=False, duplicates="drop")
    except Exception:
        patient_stats["stratum"] = pd.cut(patient_stats["event_rate"], bins=3, labels=False)

    val_counts1 = patient_stats["stratum"].value_counts()
    for s_val, count in val_counts1.items():
        if count < 2:
            majority = val_counts1.index[0]
            patient_stats.loc[patient_stats["stratum"] == s_val, "stratum"] = majority

    val_test_frac = val_frac + test_frac
    if len(patient_stats["stratum"].unique()) > 1 and (patient_stats["stratum"].value_counts() >= 2).all():
        sss1 = StratifiedShuffleSplit(n_splits=1, test_size=val_test_frac, random_state=seed)
        train_idx, val_test_idx = next(sss1.split(patient_stats["patient_id"], patient_stats["stratum"]))
    else:
        ss1 = ShuffleSplit(n_splits=1, test_size=val_test_frac, random_state=seed)
        train_idx, val_test_idx = next(ss1.split(patient_stats["patient_id"]))

    train_patients = patient_stats.iloc[train_idx].copy()
    val_test_patients = patient_stats.iloc[val_test_idx].copy()

    test_relative_frac = test_frac / val_test_frac
    val_counts2 = val_test_patients["stratum"].value_counts()
    if len(val_counts2) > 1 and (val_counts2 >= 2).all():
        try:
            sss2 = StratifiedShuffleSplit(n_splits=1, test_size=test_relative_frac, random_state=seed + 1)
            val_idx, test_idx = next(sss2.split(val_test_patients["patient_id"], val_test_patients["stratum"]))
        except ValueError:
            ss2 = ShuffleSplit(n_splits=1, test_size=test_relative_frac, random_state=seed + 1)
            val_idx, test_idx = next(ss2.split(val_test_patients["patient_id"]))
    else:
        ss2 = ShuffleSplit(n_splits=1, test_size=test_relative_frac, random_state=seed + 1)
        val_idx, test_idx = next(ss2.split(val_test_patients["patient_id"]))

    val_patients = val_test_patients.iloc[val_idx].copy()
    test_patients = val_test_patients.iloc[test_idx].copy()

    train_pids = set(train_patients["patient_id"])
    val_pids = set(val_patients["patient_id"])
    test_pids = set(test_patients["patient_id"])

    assert len(train_pids.intersection(val_pids)) == 0, "Data leakage detected: Train and Val overlap!"
    assert len(train_pids.intersection(test_pids)) == 0, "Data leakage detected: Train and Test overlap!"
    assert len(val_pids.intersection(test_pids)) == 0, "Data leakage detected: Val and Test overlap!"

    train_df = df[df["patient_id"].isin(train_pids)].copy()
    val_df = df[df["patient_id"].isin(val_pids)].copy()
    test_df = df[df["patient_id"].isin(test_pids)].copy()

    summary = {
        "train": {
            "num_patients": len(train_pids),
            "total_rows": len(train_df),
            "event_rate": float(train_df["event_next_24h"].mean()),
        },
        "validation": {
            "num_patients": len(val_pids),
            "total_rows": len(val_df),
            "event_rate": float(val_df["event_next_24h"].mean()),
        },
        "test": {
            "num_patients": len(test_pids),
            "total_rows": len(test_df),
            "event_rate": float(test_df["event_next_24h"].mean()),
        },
    }

    return train_df, val_df, test_df, summary


def compute_calibration_slope_intercept(
    y_true: np.ndarray,
    y_prob: np.ndarray,
    eps: float = 1e-6,
) -> Tuple[float, float]:
    """Compute calibration slope and intercept via univariate logistic regression on logit score.

    Model: logit(P(Y=1)) = intercept + slope * logit(y_prob)
    Perfect calibration corresponds to slope = 1.0 and intercept = 0.0.
    """
    clipped_p = np.clip(y_prob, eps, 1.0 - eps)
    logit_p = np.log(clipped_p / (1.0 - clipped_p)).reshape(-1, 1)

    # Use large C to approximate unregularized maximum likelihood calibration regression
    lr = LogisticRegression(solver="lbfgs", C=1e5, max_iter=1000)
    lr.fit(logit_p, y_true)

    slope = float(lr.coef_[0][0])
    intercept = float(lr.intercept_[0])
    return round(slope, 4), round(intercept, 4)


def choose_decision_threshold(
    y_val: np.ndarray,
    y_prob_val: np.ndarray,
    rule: str = "maximize_f1",
) -> Tuple[float, Dict[str, Any]]:
    """Choose the decision threshold on the validation set according to an explicit rule.

    Args:
        y_val: True validation labels.
        y_prob_val: Calibrated validation predicted probabilities.
        rule: Threshold selection rule ('maximize_f1' or 'maximize_f2').

    Returns:
        Chosen threshold and rule metadata dictionary.
    """
    precisions, recalls, thresholds = precision_recall_curve(y_val, y_prob_val)

    if rule == "maximize_f2":
        beta = 2.0
        beta_sq = beta**2
        scores = (1 + beta_sq) * (precisions * recalls) / (beta_sq * precisions + recalls + 1e-10)
        rule_desc = "Maximize F2 score on validation set (prioritizing recall for clinical risk detection)"
    else:
        scores = 2 * (precisions * recalls) / (precisions + recalls + 1e-10)
        rule_desc = "Maximize F1 score on validation set (harmonic balance of precision and recall)"

    best_idx = int(np.argmax(scores))
    chosen_threshold = float(thresholds[best_idx]) if best_idx < len(thresholds) else 0.50

    metadata = {
        "rule": rule,
        "rule_description": rule_desc,
        "validation_score_at_threshold": round(float(scores[best_idx]), 4),
        "validation_precision_at_threshold": round(float(precisions[best_idx]), 4),
        "validation_recall_at_threshold": round(float(recalls[best_idx]), 4),
        "threshold": round(chosen_threshold, 4),
    }

    return chosen_threshold, metadata


def compute_metrics(
    y_true: np.ndarray,
    y_prob: np.ndarray,
    threshold: float = 0.5,
) -> Dict[str, Any]:
    """Compute comprehensive diagnostic performance metrics at one explicitly stated threshold.

    Guarantees strict reconciliation: precision = TP / (TP + FP) and recall = TP / (TP + FN).
    """
    base_rate = float(np.mean(y_true))
    base_rate_brier = float(np.mean((y_true - base_rate) ** 2))

    y_pred = (y_prob >= threshold).astype(int)
    tn, fp, fn, tp = confusion_matrix(y_true, y_pred, labels=[0, 1]).ravel()

    calc_precision = float(tp / (tp + fp)) if (tp + fp) > 0 else 0.0
    calc_recall = float(tp / (tp + fn)) if (tp + fn) > 0 else 0.0

    sk_precision = float(precision_score(y_true, y_pred, zero_division=0))
    sk_recall = float(recall_score(y_true, y_pred, zero_division=0))

    # Assert exact arithmetic reconciliation
    assert abs(calc_precision - sk_precision) < 1e-4, f"Precision mismatch: {calc_precision} != {sk_precision}"
    assert abs(calc_recall - sk_recall) < 1e-4, f"Recall mismatch: {calc_recall} != {sk_recall}"

    f1 = float(f1_score(y_true, y_pred, zero_division=0))

    slope, intercept = compute_calibration_slope_intercept(y_true, y_prob)

    return {
        "roc_auc": round(float(roc_auc_score(y_true, y_prob)), 4),
        "pr_auc": round(float(average_precision_score(y_true, y_prob)), 4),
        "brier_score": round(float(brier_score_loss(y_true, y_prob)), 4),
        "base_rate_brier_baseline": round(base_rate_brier, 4),
        "brier_improvement_vs_baseline": round(base_rate_brier - float(brier_score_loss(y_true, y_prob)), 4),
        "calibration_slope": slope,
        "calibration_intercept": intercept,
        "decision_threshold": round(float(threshold), 4),
        "precision": round(calc_precision, 4),
        "recall": round(calc_recall, 4),
        "f1": round(f1, 4),
        "confusion_matrix": {
            "true_negatives": int(tn),
            "false_positives": int(fp),
            "false_negatives": int(fn),
            "true_positives": int(tp),
        },
        "reconciliation_check": {
            "tp": int(tp),
            "fp": int(fp),
            "fn": int(fn),
            "tn": int(tn),
            "tp_plus_fp": int(tp + fp),
            "tp_plus_fn": int(tp + fn),
            "reconciled_precision_formula": f"{tp} / ({tp} + {fp}) = {calc_precision:.4f}",
            "reconciled_recall_formula": f"{tp} / ({tp} + {fn}) = {calc_recall:.4f}",
            "verified": True,
        },
    }


def compute_alert_burden(
    df: pd.DataFrame,
    y_prob: np.ndarray,
    threshold: float,
    cooldown_hours: int = 6,
    lookback_hours: int = 24,
) -> Dict[str, Any]:
    """Compute clinical alert-burden metrics by merging consecutive alerts into episodes.

    Args:
        df: DataFrame containing patient_id, timestamp, and event_next_24h.
        y_prob: Predicted probabilities aligned with df rows.
        threshold: Alert decision threshold.
        cooldown_hours: Minimum hours between distinct alert episodes (default 6h).
        lookback_hours: Maximum window prior to true event for an alert to count (default 24h).

    Returns:
        Dictionary of alert burden metrics.
    """
    eval_df = df.copy()
    eval_df["y_prob"] = y_prob
    eval_df["alert"] = (y_prob >= threshold).astype(int)

    total_hours = len(eval_df)
    total_patient_days = total_hours / 24.0

    alert_episodes: List[Tuple[str, int]] = []
    true_event_episodes: List[Tuple[str, int]] = []

    for pid, group in eval_df.groupby("patient_id"):
        group = group.sort_values("timestamp")
        alerts = group["alert"].to_numpy()
        events = group["event_next_24h"].to_numpy()

        last_alert_idx = -9999
        for i, a in enumerate(alerts):
            if a == 1:
                if i - last_alert_idx > cooldown_hours:
                    alert_episodes.append((pid, i))
                last_alert_idx = i

        last_event_idx = -9999
        for i, e in enumerate(events):
            if e == 1:
                if i - last_event_idx > cooldown_hours:
                    true_event_episodes.append((pid, i))
                last_event_idx = i

    total_alerts = len(alert_episodes)
    alerts_per_patient_day = total_alerts / total_patient_days if total_patient_days > 0 else 0.0

    from collections import defaultdict

    pat_alerts: Dict[str, List[int]] = defaultdict(list)
    for pid, idx in alert_episodes:
        pat_alerts[pid].append(idx)

    preceded_count = 0
    lead_times: List[int] = []

    for pid, ev_idx in true_event_episodes:
        relevant = [a_idx for a_idx in pat_alerts[pid] if 0 <= (ev_idx - a_idx) <= lookback_hours]
        if relevant:
            preceded_count += 1
            lead_times.append(ev_idx - min(relevant))

    frac_preceded = preceded_count / len(true_event_episodes) if true_event_episodes else 0.0
    median_lead_time = float(np.median(lead_times)) if lead_times else 0.0

    return {
        "cooldown_hours": cooldown_hours,
        "lookback_hours": lookback_hours,
        "total_patient_days": round(float(total_patient_days), 1),
        "total_alert_episodes": total_alerts,
        "alerts_per_patient_day": round(float(alerts_per_patient_day), 4),
        "total_true_event_episodes": len(true_event_episodes),
        "events_preceded_by_alert_within_24h": preceded_count,
        "fraction_events_preceded_24h": round(float(frac_preceded), 4),
        "median_lead_time_hours": round(float(median_lead_time), 2),
    }


def compute_patient_bootstrap_ci(
    test_df: pd.DataFrame,
    pipeline: Any,
    feature_cols: List[str],
    n_bootstrap: int = 150,
    seed: int = 42,
) -> Dict[str, Dict[str, float]]:
    """Compute cluster bootstrap 95% confidence intervals by resampling patients."""
    rng = np.random.default_rng(seed)
    unique_patients = test_df["patient_id"].unique()
    n_pats = len(unique_patients)

    boot_roc: List[float] = []
    boot_pr: List[float] = []
    boot_brier: List[float] = []

    for _ in range(n_bootstrap):
        sampled_pids = rng.choice(unique_patients, size=n_pats, replace=True)
        sampled_frames = [test_df[test_df["patient_id"] == pid] for pid in sampled_pids]
        boot_df = pd.concat(sampled_frames, ignore_index=True)

        y_true = boot_df["event_next_24h"].to_numpy()
        if len(np.unique(y_true)) < 2:
            continue
        X_test = boot_df[feature_cols]
        y_prob = pipeline.predict_proba(X_test)[:, 1]

        boot_roc.append(roc_auc_score(y_true, y_prob))
        boot_pr.append(average_precision_score(y_true, y_prob))
        boot_brier.append(brier_score_loss(y_true, y_prob))

    def get_ci(arr: List[float]) -> Dict[str, float]:
        if not arr:
            return {"mean": 0.0, "ci_lower": 0.0, "ci_upper": 0.0}
        return {
            "mean": round(float(np.mean(arr)), 4),
            "ci_lower_95": round(float(np.percentile(arr, 2.5)), 4),
            "ci_upper_95": round(float(np.percentile(arr, 97.5)), 4),
        }

    return {
        "roc_auc_ci": get_ci(boot_roc),
        "pr_auc_ci": get_ci(boot_pr),
        "brier_score_ci": get_ci(boot_brier),
    }


def run_ablation_study(
    train_df: pd.DataFrame,
    val_df: pd.DataFrame,
    test_df: pd.DataFrame,
    all_feature_cols: List[str],
    base_model_type: str = "logistic_regression",
    seed: int = 42,
) -> Dict[str, Dict[str, Any]]:
    """Perform feature ablation by removing pollution, wearable, and adherence feature groups."""
    pollution_features = [c for c in all_feature_cols if c.startswith("pm25_") or c.startswith("pm10_")]
    wearable_features = [
        c
        for c in all_feature_cols
        if c.startswith("respiratory_rate_")
        or c.startswith("rr_")
        or c.startswith("heart_rate_")
        or c.startswith("hr_")
        or c.startswith("hrv_")
        or c.startswith("spo2_")
        or c.startswith("sleep_")
        or c.startswith("steps_")
    ]
    adherence_features = ["controller_adherence_7d"]

    groups = {
        "no_pollution": {
            "active_cols": [c for c in all_feature_cols if c not in pollution_features],
            "removed_features": pollution_features,
        },
        "no_wearables": {
            "active_cols": [c for c in all_feature_cols if c not in wearable_features],
            "removed_features": wearable_features,
        },
        "no_adherence": {
            "active_cols": [c for c in all_feature_cols if c not in adherence_features],
            "removed_features": adherence_features,
        },
    }

    y_train = train_df["event_next_24h"].to_numpy()
    y_val = val_df["event_next_24h"].to_numpy()
    y_test = test_df["event_next_24h"].to_numpy()

    ablation_results = {}
    for ablation_name, group_info in groups.items():
        active_cols = group_info["active_cols"]
        removed_cols = group_info["removed_features"]

        if base_model_type == "logistic_regression":
            pipe = Pipeline(
                [
                    ("imputer", SimpleImputer(strategy="median")),
                    ("scaler", StandardScaler()),
                    ("clf", LogisticRegression(max_iter=1000, random_state=seed)),
                ]
            )
        else:
            pipe = Pipeline(
                [
                    ("imputer", SimpleImputer(strategy="median")),
                    (
                        "clf",
                        RandomForestClassifier(
                            n_estimators=100,
                            max_depth=12,
                            min_samples_leaf=10,
                            n_jobs=-1,
                            random_state=seed,
                        ),
                    ),
                ]
            )

        pipe.fit(train_df[active_cols], y_train)

        # Calibrate ablation model on validation set
        val_probs = pipe.predict_proba(val_df[active_cols])[:, 1]
        iso = IsotonicRegression(out_of_bounds="clip")
        iso.fit(val_probs, y_val)

        test_raw = pipe.predict_proba(test_df[active_cols])[:, 1]
        test_cal = iso.predict(test_raw)

        metrics = compute_metrics(y_test, test_cal)
        ablation_results[ablation_name] = {
            "num_features": len(active_cols),
            "features_removed_count": len(removed_cols),
            "features_removed": removed_cols,
            "roc_auc": metrics["roc_auc"],
            "pr_auc": metrics["pr_auc"],
            "brier_score": metrics["brier_score"],
        }

    return ablation_results


def plot_diagnostic_curves(
    y_test: np.ndarray,
    y_prob_raw: np.ndarray,
    y_prob_cal: np.ndarray,
    selected_name: str,
    output_dir: Union[str, Path] = "models",
) -> Dict[str, str]:
    """Plot and save ROC, PR, and probability calibration curves (before and after calibration)."""
    out_dir = Path(output_dir)
    out_dir.mkdir(parents=True, exist_ok=True)

    # 1. ROC and PR Curves
    fig, (ax1, ax2) = plt.subplots(1, 2, figsize=(14, 5))

    fpr, tpr, _ = roc_curve(y_test, y_prob_cal)
    ax1.plot(fpr, tpr, label=f"{selected_name.replace('_', ' ').title()} (AUC = {roc_auc_score(y_test, y_prob_cal):.3f})", color="#2980b9", lw=2)
    ax1.plot([0, 1], [0, 1], "k--", alpha=0.5, label="Chance")
    ax1.set_title("Test ROC Curve (Calibrated Model)")
    ax1.set_xlabel("False Positive Rate")
    ax1.set_ylabel("True Positive Rate")
    ax1.legend(loc="lower right")
    ax1.grid(True, alpha=0.3)

    prec, rec, _ = precision_recall_curve(y_test, y_prob_cal)
    baseline_rate = float(np.mean(y_test))
    ax2.plot(rec, prec, label=f"{selected_name.replace('_', ' ').title()} (PR-AUC = {average_precision_score(y_test, y_prob_cal):.3f})", color="#27ae60", lw=2)
    ax2.axhline(baseline_rate, color="gray", linestyle="--", label=f"Base Rate ({baseline_rate:.3f})")
    ax2.set_title("Test Precision-Recall Curve")
    ax2.set_xlabel("Recall")
    ax2.set_ylabel("Precision")
    ax2.legend(loc="upper right")
    ax2.grid(True, alpha=0.3)

    plt.tight_layout()
    roc_pr_path = out_dir / "roc_pr_curve.png"
    plt.savefig(roc_pr_path, dpi=150)
    plt.close()

    # 2. Calibration Curve (Before vs After)
    fig, ax = plt.subplots(figsize=(8, 6))

    prob_true_raw, prob_pred_raw = calibration_curve(y_test, y_prob_raw, n_bins=10)
    prob_true_cal, prob_pred_cal = calibration_curve(y_test, y_prob_cal, n_bins=10)

    slope_raw, int_raw = compute_calibration_slope_intercept(y_test, y_prob_raw)
    slope_cal, int_cal = compute_calibration_slope_intercept(y_test, y_prob_cal)

    brier_raw = brier_score_loss(y_test, y_prob_raw)
    brier_cal = brier_score_loss(y_test, y_prob_cal)
    base_brier = baseline_rate * (1.0 - baseline_rate)

    ax.plot([0, 1], [0, 1], "k--", label="Perfect Calibration (slope=1, int=0)", alpha=0.7)
    ax.axhline(baseline_rate, color="purple", linestyle=":", alpha=0.6, label=f"Base-Rate Prevalence ({baseline_rate:.3f})")
    ax.plot(
        prob_pred_raw,
        prob_true_raw,
        "s--",
        color="#e74c3c",
        label=f"Before Calibration (Brier={brier_raw:.4f}, slope={slope_raw:.2f}, int={int_raw:.2f})",
        alpha=0.8,
    )
    ax.plot(
        prob_pred_cal,
        prob_true_cal,
        "o-",
        color="#27ae60",
        label=f"After Isotonic Calibration (Brier={brier_cal:.4f}, slope={slope_cal:.2f}, int={int_cal:.2f})",
        lw=2,
    )

    ax.set_xlabel("Mean Predicted Probability")
    ax.set_ylabel("Observed Event Fraction")
