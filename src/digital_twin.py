"""Digital Twin core state representation, dynamic updates, and what-if simulation.

Key Capabilities:
- DigitalTwin class maintaining stateful patient profiles and observation streams.
- Dynamic twin state updates via `update_twin(patient_id, latest_observations)`.
- Personalized Baseline: Computed over a 14-30 day window excluding the most recent 72 hours
  to prevent acute prodromal deterioration from contaminating the stable personal norm.
- Coherent Counterfactual Overrides: In `what_if`, updates all dependent features consistently
  (e.g., pm25_level updates all rolling mean/max metrics; respiratory_rate_shift updates all RR derivations).
- Data Quality & Stale-Data Flags: Detects channels forward-filled for > 6 hours and flags them in
  `current_state["data_quality"]` with hours-stale metrics.
- Model Response to Hypothetical Input: Clear documentation and tagging for all counterfactual scenarios
  (never mutating stored historical data).
- Signal-Family Grouped Explanations: Integrates with `src.explain_prediction` to present primary
  family-level logit contributions alongside transparent clinical reason codes.

Independent of Streamlit.
"""

