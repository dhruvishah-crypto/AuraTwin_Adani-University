class DigitalTwin:
    """Stateful healthcare Digital Twin representation for asthma exacerbation risk management.

    Maintains patient profiles, observation streams, rolling personalized baselines,
    data quality / staleness tracking, and chronological prediction histories.
    Supports non-destructive counterfactual simulation ('model response to hypothetical input').
    """

    def __init__(
        self,
        patient_id: Optional[str] = None,
        data_dir: Union[str, Path] = "data",
        model_path: Union[str, Path] = "models/model.joblib",
        feature_columns_path: Union[str, Path] = "models/feature_columns.json",
        metrics_path: Union[str, Path] = "models/metrics.json",
    ):
        self.active_patient_id = patient_id
        self.data_dir = Path(data_dir)
        self.model_path = Path(model_path)
        self.feature_columns_path = Path(feature_columns_path)
        self.metrics_path = Path(metrics_path)

        # Initialize predictor
        self.predictor = RiskPredictor(
            model_path=self.model_path,
            feature_columns_path=self.feature_columns_path,
            metrics_path=self.metrics_path,
        )

        # In-memory twin stores keyed by patient_id
        self.profiles: Dict[str, Dict[str, Any]] = {}
        self.observations: Dict[str, pd.DataFrame] = {}
        self.raw_observations: Dict[str, pd.DataFrame] = {}  # Tracks un-imputed values for staleness
        self.personal_baselines: Dict[str, Dict[str, float]] = {}
        self.current_state: Dict[str, Dict[str, Any]] = {}
        self.state_history: Dict[str, List[Dict[str, Any]]] = {}

        # Cached cohort references for on-demand loading
        self._patients_df: Optional[pd.DataFrame] = None
        self._pollution_df: Optional[pd.DataFrame] = None

        if patient_id is not None:
            self.load_patient(patient_id)

    # -------------------------------------------------------------------------
    # Cohort Data Loaders
    # -------------------------------------------------------------------------
    def _get_patients_df(self) -> pd.DataFrame:
        """Load and cache the patients EHR table."""
        if self._patients_df is None:
            candidates = [
                self.data_dir / "patients.csv",
                self.data_dir / "sample_patients.csv",
            ]
            for p in candidates:
                if p.is_file():
                    self._patients_df = pd.read_csv(p)
                    break
            if self._patients_df is None:
                raise FileNotFoundError(f"Patients EHR table not found in {self.data_dir}")
        return self._patients_df

    def _get_pollution_df(self) -> pd.DataFrame:
        """Load and cache the ambient pollution series."""
        if self._pollution_df is None:
            candidates = [
                self.data_dir / "sample_pollution.csv",
                self.data_dir / "pollution.csv",
            ]
            for p in candidates:
                if p.is_file():
                    df = pd.read_csv(p)
                    df["timestamp"] = pd.to_datetime(df["timestamp"])
                    self._pollution_df = df
                    break
            if self._pollution_df is None:
                dates = pd.date_range("2026-08-01", periods=240, freq="h")
                self._pollution_df = pd.DataFrame(
                    {
                        "timestamp": dates,
                        "pm25": np.full(len(dates), 45.0),
                        "pm10": np.full(len(dates), 85.0),
                    }
                )
        return self._pollution_df

    # -------------------------------------------------------------------------
    # Profile & State Management
    # -------------------------------------------------------------------------
    def get_patient_profile(self, patient_id: str) -> Dict[str, Any]:
        """Load or retrieve the static EHR profile for a patient."""
        if patient_id in self.profiles:
            return self.profiles[patient_id]

        patients_df = self._get_patients_df()
        pat_rows = patients_df[patients_df["patient_id"] == patient_id]

        if len(pat_rows) == 0:
            profile = {
                "patient_id": patient_id,
                "age": 42,
                "sex": "F",
                "asthma_severity": "Moderate",
                "baseline_resp_rate": 16.0,
                "baseline_spo2": 96.0,
                "comorbidities": "allergic_rhinitis",
                "controller_prescribed": 1,
                "prior_exacerbations_12m": 1,
                "pollution_sensitivity": "Medium",
                "provenance": "simulated",
            }
        else:
            profile = pat_rows.iloc[0].to_dict()

        self.profiles[patient_id] = profile
        return profile

    def load_patient(self, patient_id: str) -> None:
        """Initialize patient data structures and load baseline records."""
        self.active_patient_id = patient_id
        profile = self.get_patient_profile(patient_id)

        if patient_id not in self.state_history:
            self.state_history[patient_id] = []

        if patient_id not in self.observations or self.observations[patient_id].empty:
            seeded = False
            for ts_path in [
                self.data_dir / "sample_wearables.csv",
                self.data_dir / "patient_timeseries.csv",
            ]:
                if ts_path.is_file():
                    ts_df = pd.read_csv(ts_path)
                    pat_ts = ts_df[ts_df["patient_id"] == patient_id].copy()
                    if not pat_ts.empty:
                        pat_ts["timestamp"] = pd.to_datetime(pat_ts["timestamp"])
                        pat_ts = pat_ts.sort_values("timestamp").reset_index(drop=True)
                        self.raw_observations[patient_id] = pat_ts.copy()
                        self.observations[patient_id] = pat_ts.copy()
                        seeded = True
                        break

            if not seeded:
                init_time = pd.Timestamp("2026-08-01 00:00:00")
                init_obs = pd.DataFrame(
                    [
                        {
                            "patient_id": patient_id,
                            "timestamp": init_time,
                            "respiratory_rate": float(profile.get("baseline_resp_rate", 16.0)),
                            "heart_rate": 72.0,
                            "hrv_rmssd_ms": 38.0,
                            "spo2": float(profile.get("baseline_spo2", 96.5)),
                            "sleep_hours": 7.0,
                            "steps": 120,
                            "controller_taken": int(profile.get("controller_prescribed", 1)),
                            "rescue_puffs": 0,
                            "symptom_score": 1,
                            "provenance": "simulated",
                        }
                    ]
                )
                self.raw_observations[patient_id] = init_obs.copy()
                self.observations[patient_id] = init_obs.copy()

        self.compute_personal_baseline(patient_id)

    # -------------------------------------------------------------------------
    # Personalization & Rolling Baseline
    # -------------------------------------------------------------------------
    def compute_personal_baseline(self, patient_id: str) -> Dict[str, float]:
        """Compute personalized rolling baseline metrics over a 14-30 day window excluding recent 72 hours.

        Methodological rationale:
        In clinical exacerbation dynamics, acute prodromal deterioration begins 6 to 72 hours
        prior to attack onset (accelerating rescue use, tachycardia, tachypnea, SpO2 dips).
        Excluding the most recent 72 hours prevents ongoing acute deterioration from inflating
        the patient's baseline norm, preserving sensitivity to acute divergences.
        A 14-day (336h) to 30-day (720h) lookback captures a robust personal norm across
        circadian and weekly cycles.

        If fewer than 72 hours of total observations exist, falls back cleanly to static EHR baselines.
        """
        profile = self.get_patient_profile(patient_id)
        obs_df = self.observations.get(patient_id)

        base_rr = float(profile.get("baseline_resp_rate", 16.0))
        base_spo2 = float(profile.get("baseline_spo2", 96.0))

        if obs_df is None or len(obs_df) <= 72:
            # Fallback to static EHR baseline when insufficient pre-prodromal history exists
            baseline = {
                "usual_respiratory_rate": base_rr,
                "usual_heart_rate": 72.0,
                "usual_hrv": 35.0,
                "usual_spo2": base_spo2,
                "usual_pm25": 40.0,
                "usual_controller_adherence": 1.0,
                "usual_rescue_puffs": 0.2,
                "usual_symptom_score": 1.0,
                "baseline_resp_rate": base_rr,
                "baseline_spo2": base_spo2,
                "baseline_window_hours": 0,
                "excluded_recent_hours": 0,
            }
        else:
            # Slicing window: excludes most recent 72 hours; looks back 14-30 days (336 to 720 hours)
            window_end = len(obs_df) - 72
            window_start = max(0, window_end - 720)
            baseline_window = obs_df.iloc[window_start:window_end]

            rr_vals = baseline_window["respiratory_rate"].dropna() if "respiratory_rate" in baseline_window else pd.Series([], dtype=float)
            hr_vals = baseline_window["heart_rate"].dropna() if "heart_rate" in baseline_window else pd.Series([], dtype=float)
            hrv_vals = baseline_window["hrv_rmssd_ms"].dropna() if "hrv_rmssd_ms" in baseline_window else pd.Series([], dtype=float)
            spo2_vals = baseline_window["spo2"].dropna() if "spo2" in baseline_window else pd.Series([], dtype=float)
            adh_vals = baseline_window["controller_taken"].dropna() if "controller_taken" in baseline_window else pd.Series([], dtype=float)
            rescue_vals = baseline_window["rescue_puffs"].dropna() if "rescue_puffs" in baseline_window else pd.Series([], dtype=float)
            symptom_vals = baseline_window["symptom_score"].dropna() if "symptom_score" in baseline_window else pd.Series([], dtype=float)

            pm25_val = 40.0
            if "pm25" in baseline_window:
                pm25_vals = baseline_window["pm25"].dropna()
                if not pm25_vals.empty:
                    pm25_val = float(pm25_vals.mean())

            baseline = {
                "usual_respiratory_rate": round(float(rr_vals.mean()), 1) if not rr_vals.empty else base_rr,
                "usual_heart_rate": round(float(hr_vals.mean()), 1) if not hr_vals.empty else 72.0,
                "usual_hrv": round(float(hrv_vals.mean()), 1) if not hrv_vals.empty else 35.0,
                "usual_spo2": round(float(spo2_vals.mean()), 1) if not spo2_vals.empty else base_spo2,
                "usual_pm25": round(pm25_val, 1),
                "usual_controller_adherence": round(float(adh_vals.mean()), 2) if not adh_vals.empty else 1.0,
                "usual_rescue_puffs": round(float(rescue_vals.sum() / max(1.0, len(baseline_window) / 24.0)), 2),
                "usual_symptom_score": round(float(symptom_vals.mean()), 1) if not symptom_vals.empty else 1.0,
                "baseline_resp_rate": base_rr,
                "baseline_spo2": base_spo2,
                "baseline_window_hours": len(baseline_window),
                "excluded_recent_hours": 72,
            }

        self.personal_baselines[patient_id] = baseline
        return baseline

    # -------------------------------------------------------------------------
    # Stale-Data Detection
    # -------------------------------------------------------------------------
    def assess_data_quality(self, patient_id: str, threshold_hours: int = 6) -> Dict[str, Any]:
        """Assess sensor data quality and flag channels forward-filled for > 6 hours.

        Args:
            patient_id: Patient ID.
            threshold_hours: Maximum allowable staleness before flagging (default 6h).

        Returns:
            Dictionary containing stale_channels, hours_stale per channel, and quality flags.
        """
        raw_df = self.raw_observations.get(patient_id)
        if raw_df is None or raw_df.empty:
            return {"has_stale_data": False, "stale_channels": {}, "flags": []}

        channels = [
            "respiratory_rate",
            "heart_rate",
            "spo2",
            "hrv_rmssd_ms",
            "pm25",
            "symptom_score",
            "rescue_puffs",
        ]

        stale_channels: Dict[str, Dict[str, Any]] = {}
        flags: List[str] = []

        for ch in channels:
            if ch not in raw_df.columns:
                continue

            series = raw_df[ch].tolist()
            # Count consecutive trailing NaNs (unobserved / forward-filled hours)
            hours_stale = 0
            for val in reversed(series):
                if val is None or pd.isna(val):
                    hours_stale += 1
                else:
                    break

            if hours_stale > threshold_hours:
                stale_channels[ch] = {
                    "hours_stale": hours_stale,
                    "threshold_hours": threshold_hours,
                    "status": "stale",
                }
                flags.append(
                    f"Telemetry staleness: {ch.replace('_', ' ')} has been forward-filled for {hours_stale} hours "
                    f"(exceeds {threshold_hours}h clinical staleness threshold)"
                )

        return {
            "has_stale_data": len(stale_channels) > 0,
            "stale_channels": stale_channels,
            "flags": flags,
        }

    # -------------------------------------------------------------------------
    # Twin State Update
    # -------------------------------------------------------------------------
    def update_twin(
        self,
        patient_id: Optional[str] = None,
        latest_observations: Optional[Union[Dict[str, Any], pd.DataFrame, List[Dict[str, Any]]]] = None,
    ) -> Dict[str, Any]:
        """Update the digital twin state for a patient with new sensor/EHR observations.

        Actions:
        1. Loads historical patient profile.
        2. Ingests latest observations into historical time-series stream.
        3. Updates the personalized per-patient rolling baseline (14-30d excluding recent 72h).
        4. Detects sensor staleness and populates current_state["data_quality"].
        5. Recomputes engineered feature vectors and 24-hour calibrated risk forecast.
        6. Computes signal-family grouped explanations, reason codes, and attributions.
        7. Appends the state to the chronological history.
        8. Returns profile, current_state, forecast, contributing_signals, and history.

        Args:
            patient_id: Target patient identifier (defaults to active_patient_id).
            latest_observations: New observation dict, DataFrame, or list of dicts.

        Returns:
            Dictionary with profile, current_state, forecast, contributing_signals, history.
        """
        pid = patient_id or self.active_patient_id
        if pid is None:
            raise ValueError("patient_id must be provided or active_patient_id must be set.")

        self.active_patient_id = pid
        profile = self.get_patient_profile(pid)

        if pid not in self.observations or self.observations[pid].empty:
            self.load_patient(pid)

        existing_obs = self.observations[pid]
        existing_raw = self.raw_observations.get(pid, existing_obs.copy())

        # Ingest new observations if supplied
        if latest_observations is not None:
            if isinstance(latest_observations, dict):
                new_df = pd.DataFrame([latest_observations])
            elif isinstance(latest_observations, list):
                new_df = pd.DataFrame(latest_observations)
            elif isinstance(latest_observations, pd.DataFrame):
                new_df = latest_observations.copy()
            else:
                raise ValueError(f"Unsupported latest_observations type: {type(latest_observations)}")

            if "patient_id" not in new_df.columns:
                new_df["patient_id"] = pid
            if "timestamp" in new_df.columns:
                new_df["timestamp"] = pd.to_datetime(new_df["timestamp"])
            else:
                last_time = existing_obs["timestamp"].max() if not existing_obs.empty else pd.Timestamp("2026-08-01 00:00:00")
                new_df["timestamp"] = last_time + pd.Timedelta(hours=1)

            # Record raw un-forward-filled incoming observations for data quality tracking
            raw_combined = pd.concat([existing_raw, new_df], ignore_index=True)
            raw_combined = raw_combined.drop_duplicates(subset=["timestamp"], keep="last")
            raw_combined = raw_combined.sort_values("timestamp").reset_index(drop=True)
            self.raw_observations[pid] = raw_combined

            # Forward-fill missing sensor values for feature pipeline
            imputed_combined = pd.concat([existing_obs, new_df], ignore_index=True)
            for col in [
                "respiratory_rate",
                "heart_rate",
                "spo2",
                "hrv_rmssd_ms",
                "sleep_hours",
                "steps",
                "controller_taken",
                "rescue_puffs",
                "symptom_score",
            ]:
                if col in imputed_combined.columns:
                    imputed_combined[col] = imputed_combined[col].ffill().fillna(0)

            imputed_combined = imputed_combined.drop_duplicates(subset=["timestamp"], keep="last")
            imputed_combined = imputed_combined.sort_values("timestamp").reset_index(drop=True)
            self.observations[pid] = imputed_combined

        obs_stream = self.observations[pid]
        pollution_df = self._get_pollution_df()

        # Update per-patient personal rolling baseline (14-30d excluding recent 72h)
        personal_baseline = self.compute_personal_baseline(pid)

        # Assess data quality & staleness
        data_quality = self.assess_data_quality(pid, threshold_hours=6)

        # Recompute feature matrix for this patient
        pat_df_single = pd.DataFrame([profile])
        features_df = engineer_patient_features(pat_df_single, obs_stream, pollution_df)

        # Extract latest point-in-time feature vector
        latest_feature_row = features_df.iloc[-1]
        latest_timestamp = latest_feature_row["timestamp"]
        feature_dict = {col: float(latest_feature_row[col]) for col in self.predictor.feature_columns if col in latest_feature_row}

        # Predict 24-hour exacerbation risk
        forecast = self.predictor.predict_risk(feature_dict)
        forecast["source"] = "observed"

        # Generate transparent clinical reason codes and signal family grouped attributions
        contributing_signals = explain_prediction(
            model=self.predictor.model,
            feature_vector=feature_dict,
            personal_baseline=personal_baseline,
            is_scenario=False,
        )

        latest_obs_row = obs_stream.iloc[-1].to_dict()

        def _safe_val(v: Any, default: float) -> float:
            if v is None or pd.isna(v):
                return default
            try:
                return float(v)
            except (ValueError, TypeError):
                return default

        latest_vitals = {
            "respiratory_rate": _safe_val(latest_obs_row.get("respiratory_rate"), float(profile.get("baseline_resp_rate", 16.0))),
            "heart_rate": _safe_val(latest_obs_row.get("heart_rate"), 72.0),
            "spo2": _safe_val(latest_obs_row.get("spo2"), float(profile.get("baseline_spo2", 96.0))),
            "hrv_rmssd_ms": _safe_val(latest_obs_row.get("hrv_rmssd_ms"), 35.0),
            "symptom_score": _safe_val(latest_obs_row.get("symptom_score"), 1.0),
            "rescue_puffs": int(round(_safe_val(latest_obs_row.get("rescue_puffs"), 0.0))),
            "controller_taken": int(round(_safe_val(latest_obs_row.get("controller_taken"), 1.0))),
            "pm25": float(feature_dict.get("pm25_rolling_mean_24h", 40.0)),
        }

        # Construct current state representation including data quality
        current_state = {
            "patient_id": pid,
            "timestamp": str(latest_timestamp),
            "features": feature_dict,
            "personal_baseline": personal_baseline,
            "latest_vitals": latest_vitals,
            "data_quality": data_quality,
            "source": "observed",
        }
        self.current_state[pid] = current_state

        # Append to chronological state history
        history_entry = {
            "timestamp": str(latest_timestamp),
            "risk": {
                "probability": forecast["probability"],
                "risk_score_100": forecast["risk_score_100"],
                "risk_band": forecast["risk_band"],
            },
            "key_inputs": {
                "pm25_24h": round(float(feature_dict.get("pm25_rolling_mean_24h", 0.0)), 1),
                "respiratory_rate": round(latest_vitals["respiratory_rate"], 1),
                "heart_rate": round(latest_vitals["heart_rate"], 1),
                "spo2": round(latest_vitals["spo2"], 1),
                "controller_adherence_7d": round(float(feature_dict.get("controller_adherence_7d", 1.0)), 2),
                "rescue_puffs_24h": int(feature_dict.get("rescue_puffs_sum_24h", 0)),
                "symptom_score_6h": round(float(feature_dict.get("symptom_score_mean_6h", 1.0)), 1),
            },
            "source": "observed",
        }

        if pid not in self.state_history:
            self.state_history[pid] = []
        self.state_history[pid].append(history_entry)

        return {
            "profile": profile,
            "current_state": current_state,
            "forecast": forecast,
            "contributing_signals": contributing_signals,
            "history": list(self.state_history[pid]),
        }

    # -------------------------------------------------------------------------
    # Counterfactual What-If Scenario Simulation
    # -------------------------------------------------------------------------
    def what_if(
        self,
        patient_id: Optional[str] = None,
        scenario_overrides: Optional[Dict[str, Any]] = None,
    ) -> Dict[str, Any]:
        """Perform counterfactual what-if simulation ('model response to hypothetical input').

        Coherently updates all dependent features (e.g. pm25_level updates all rolling mean/max metrics;
        respiratory_rate_shift updates all RR derivations). Guarantees complete immutability
        of stored twin state, observation streams, and history.

        Args:
            patient_id: Target patient identifier.
            scenario_overrides: Dictionary of hypothetical modifications.

        Returns:
            Dictionary tagged source='model response to hypothetical input' comparing original vs scenario risk.
        """
        pid = patient_id or self.active_patient_id
        if pid is None:
            raise ValueError("patient_id must be provided or active_patient_id must be set.")

        if pid not in self.current_state:
            self.update_twin(pid)

        # 1. Non-destructive Deep Copy of Current State
        original_state = copy.deepcopy(self.current_state[pid])
        original_features = copy.deepcopy(original_state["features"])
        original_history_len = len(self.state_history.get(pid, []))
        original_obs_len = len(self.observations.get(pid, []))

        # Evaluate baseline prediction
        original_risk = self.predictor.predict_risk(original_features)
        original_risk["source"] = "observed"

        # 2. Apply Coherent Overrides to Scenario Copy
        scenario_features = copy.deepcopy(original_features)
        overrides = scenario_overrides or {}
        applied_modifications: Dict[str, Any] = {}

        # Coherent Environmental Overrides: updates all rolling PM2.5 mean/max features
        if "pm25" in overrides or "pm25_level" in overrides or "pm25_override" in overrides:
            val = float(overrides.get("pm25", overrides.get("pm25_level", overrides.get("pm25_override"))))
            scenario_features["pm25_rolling_mean_6h"] = val
            scenario_features["pm25_rolling_max_6h"] = val
            scenario_features["pm25_rolling_mean_24h"] = val
            scenario_features["pm25_rolling_max_24h"] = val
            scenario_features["pm25_rolling_mean_72h"] = val
            scenario_features["pm25_rolling_max_72h"] = val
            applied_modifications["pm25_level"] = val

        if "pm10" in overrides or "pm10_level" in overrides:
            val = float(overrides.get("pm10", overrides.get("pm10_level")))
            scenario_features["pm10_rolling_mean_24h"] = val
            scenario_features["pm10_trend_24h"] = 0.0
            applied_modifications["pm10_level"] = val

        # Coherent Controller Medication Adherence Override
        for k in ["controller_adherence", "controller_adherence_pct", "adherence", "controller_adherence_7d"]:
            if k in overrides:
                adh_val = float(overrides[k])
                if adh_val > 1.0:
                    adh_val = adh_val / 100.0
                adh_val = float(np.clip(adh_val, 0.0, 1.0))
                scenario_features["controller_adherence_7d"] = adh_val
                applied_modifications["controller_adherence_7d"] = adh_val
                break

        # Coherent Respiratory Rate Overrides & Shifts: updates all RR-derived features
        base_rr = float(scenario_features.get("baseline_resp_rate", 16.0))

        if "respiratory_rate_shift" in overrides:
            shift = float(overrides["respiratory_rate_shift"])
            scenario_features["respiratory_rate_raw"] = float(scenario_features.get("respiratory_rate_raw", 16.0)) + shift
            scenario_features["rr_rolling_mean_6h"] = float(scenario_features.get("rr_rolling_mean_6h", 16.0)) + shift
            # In clinical respiratory mechanics, an acute shift over the recent 6h window contributes proportionally
            # to the 24h rolling average as (6h / 24h = 0.25 * shift), preserving acute spike semantics and risk monotonicity
            scenario_features["rr_rolling_mean_24h"] = float(scenario_features.get("rr_rolling_mean_24h", 16.0)) + (shift * 0.25)
            scenario_features["rr_deviation_from_baseline"] = scenario_features["respiratory_rate_raw"] - base_rr
            scenario_features["rr_recent_vs_usual"] = float(scenario_features.get("rr_recent_vs_usual", 0.0)) + shift
            applied_modifications["respiratory_rate_shift"] = shift

        if "respiratory_rate" in overrides:
            rr_val = float(overrides["respiratory_rate"])
            old_rr = float(scenario_features.get("respiratory_rate_raw", 16.0))
            shift = rr_val - old_rr
            scenario_features["respiratory_rate_raw"] = rr_val
            scenario_features["rr_rolling_mean_6h"] = float(scenario_features.get("rr_rolling_mean_6h", 16.0)) + shift
            scenario_features["rr_rolling_mean_24h"] = float(scenario_features.get("rr_rolling_mean_24h", 16.0)) + (shift * 0.25)
            scenario_features["rr_deviation_from_baseline"] = rr_val - base_rr
            scenario_features["rr_recent_vs_usual"] = float(scenario_features.get("rr_recent_vs_usual", 0.0)) + shift
            applied_modifications["respiratory_rate"] = rr_val

        # Oxygen Saturation (SpO2) Overrides
        if "spo2" in overrides:
            spo2_val = float(overrides["spo2"])
            base_spo2 = float(scenario_features.get("baseline_spo2", 96.0))
            scenario_features["spo2_raw"] = spo2_val
            scenario_features["spo2_mean_6h"] = spo2_val
            scenario_features["spo2_min_6h"] = min(spo2_val, float(scenario_features.get("spo2_min_6h", spo2_val)))
            scenario_features["spo2_drop_from_baseline"] = max(0.0, base_spo2 - spo2_val)
            scenario_features["spo2_recent_vs_usual"] = spo2_val - base_spo2
            applied_modifications["spo2"] = spo2_val

        # Rescue Inhaler Usage
        if "rescue_puffs" in overrides or "rescue_puffs_24h" in overrides or "rescue_puffs_sum_24h" in overrides:
            puffs = float(overrides.get("rescue_puffs", overrides.get("rescue_puffs_24h", overrides.get("rescue_puffs_sum_24h"))))
            scenario_features["rescue_puffs_sum_24h"] = puffs
            scenario_features["rescue_puffs_sum_6h"] = min(puffs, puffs / 2.0)
            applied_modifications["rescue_puffs_sum_24h"] = puffs

        # Direct Feature Overrides
        for feat_name in self.predictor.feature_columns:
            if feat_name in overrides and feat_name not in applied_modifications:
                scenario_features[feat_name] = float(overrides[feat_name])
                applied_modifications[feat_name] = float(overrides[feat_name])

        # 3. Rerun Prediction on Hypothetical Input
        scenario_risk = self.predictor.predict_risk(scenario_features)
        scenario_risk["source"] = SCENARIO_LABEL
        scenario_risk["scenario_label"] = SCENARIO_LABEL

        # 4. Compute Risk Deltas
        delta_prob = round(float(scenario_risk["probability"] - original_risk["probability"]), 4)
        delta_score = int(scenario_risk["risk_score_100"] - original_risk["risk_score_100"])

        if delta_prob < -0.005:
            risk_direction = "decreased"
        elif delta_prob > 0.005:
            risk_direction = "increased"
        else:
            risk_direction = "unchanged"

        # 5. Explain Scenario Attribution Signals
        scenario_explanations = explain_prediction(
            model=self.predictor.model,
            feature_vector=scenario_features,
            personal_baseline=original_state.get("personal_baseline"),
            is_scenario=True,
        )

        # 6. Strict Immutability Assertions
        assert len(self.state_history.get(pid, [])) == original_history_len, "History was mutated during what-if!"
        assert len(self.observations.get(pid, [])) == original_obs_len, "Observations were mutated during what-if!"
        assert self.current_state[pid]["features"] == original_features, "Stored current state was mutated during what-if!"

        return {
            "patient_id": pid,
            "source": SCENARIO_LABEL,
            "scenario_label": SCENARIO_LABEL,
            "scenario_overrides": overrides,
            "applied_modifications": applied_modifications,
            "original_risk": original_risk,
            "scenario_risk": scenario_risk,
            "delta": {
                "delta_probability": delta_prob,
                "delta_risk_score": delta_score,
                "risk_direction": risk_direction,
            },
            "contributing_signals": scenario_explanations,
            "scenario_state": {
                "patient_id": pid,
                "timestamp": original_state.get("timestamp"),
                "features": scenario_features,
                "source": SCENARIO_LABEL,
                "scenario_label": SCENARIO_LABEL,
            },
            "disclaimer": (
                "CLINICAL DISCLAIMER: Scenario outputs represent model response to hypothetical input. "
                "Results measure simulated interactions, not real-world clinical prognosis."
            ),
        }
